"""Pure helpers shared by the Harbor adapter and its unit tests.

This module deliberately has no Harbor dependency.  It keeps command assembly
and benchmark metadata easy to test on a developer machine where Harbor is not
installed.
"""

from __future__ import annotations

import shlex
from dataclasses import dataclass


@dataclass(frozen=True)
class ModelSelection:
    provider: str
    model: str


def split_model_name(model_name: str | None, provider: str | None = None) -> ModelSelection:
    """Resolve Harbor's ``provider/model`` name to mini-harness flags.

    Harbor normally passes ``--model provider/model`` to an agent.  The
    explicit ``provider`` option is useful for local smoke tests and for model
    names that do not contain a slash.  Silent provider guessing would make a
    benchmark hard to reproduce, so an absent provider is rejected.
    """

    raw = (model_name or "").strip()
    explicit_provider = (provider or "").strip()
    if "/" in raw:
        model_provider, model = raw.split("/", 1)
        model_provider = model_provider.strip()
        model = model.strip()
        if not model_provider or not model:
            raise ValueError("model must use the form provider/model")
        if explicit_provider and explicit_provider != model_provider:
            raise ValueError(
                f"provider={explicit_provider!r} conflicts with model provider "
                f"{model_provider!r}"
            )
        return ModelSelection(model_provider, model)
    if not raw:
        raise ValueError(
            "a Harbor model is required; use --model provider/model "
            "(for example deepseek/deepseek-chat)"
        )
    if not explicit_provider:
        raise ValueError(
            "model without a provider requires the adapter's provider option"
        )
    return ModelSelection(explicit_provider, raw)


def benchmark_config(
    *,
    max_steps: int,
    max_turn_time_ms: int,
    network: str,
) -> str:
    """Return a deterministic non-interactive config for one trial.

    Approval is intentionally disabled only inside the isolated Harbor trial.
    ``network`` is validated as an experiment label, but this adapter does not
    claim to install network isolation; the current mini-harness binary only
    supports the inherited mode here. API keys are never written into this
    file; the adapter passes them via the process environment.
    """

    if max_steps <= 0:
        raise ValueError("max_steps must be positive")
    if max_turn_time_ms <= 0:
        raise ValueError("max_turn_time_ms must be positive")
    if network not in {"inherited", "offline_strict"}:
        raise ValueError("network must be inherited or offline_strict")
    if network == "offline_strict":
        raise ValueError(
            "offline_strict requires a mini-harness build with the sandbox "
            "network policy enabled; this adapter only supports inherited network"
        )
    return """# generated by benchmark/harbor/mini_harness_agent.py\n""" + (
        "[session]\n"
        f"max_steps = {max_steps}\n"
        f"max_turn_time_ms = {max_turn_time_ms}\n"
        "\n"
        "[permissions]\n"
        'read_workspace = "allow"\n'
        'edit_workspace = "allow"\n'
        'bash = "allow"\n'
    )


def run_command(
    *,
    binary: str,
    config_path: str,
    event_log: str,
    workspace: str,
    selection: ModelSelection,
    instruction: str,
) -> str:
    """Build the non-interactive command executed by Harbor.

    All user-controlled values are shell-quoted.  ``--`` is placed before the
    prompt so an issue beginning with ``-`` cannot become a CLI option.
    """

    parts = [
        binary,
        "--config",
        config_path,
        "run",
        "--event-log",
        event_log,
        "--workspace",
        workspace,
        "--provider",
        selection.provider,
        "--model",
        selection.model,
        "--",
        instruction,
    ]
    return shlex.join(parts)
